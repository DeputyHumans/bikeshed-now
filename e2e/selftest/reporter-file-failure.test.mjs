// Self-test: a spec file that fails as a whole (its timeout, its process dying, a hook, an import) leaves a FAIL record for every case it cancelled, or one of its own (SPEC §12).

/**
 * Generated fixture files run through `node --test` with the argv run.mjs
 * builds (nodeTestArgs) and the real reporter, by the Node that runs this
 * test. They are given by a path through a symlink (the OS temp directory,
 * /var → /private/var on macOS), as node names the per-file wrapper, while
 * the cases report the real path: the reporter must join the two. Each run's
 * records are read back from the JSONL file:
 *
 *   dies       a case passes; the next reports a subtest and then its process
 *              exits; a third never starts. The dying case and the third are
 *              FAIL records ("while this case ran" / "before this case
 *              started"), and the subtest keeps its path under its parent.
 *   hook       every case passes, then a top-level after() throws: one
 *              `(file)` record, with the hook's message.
 *   load       the file throws before declaring anything, with a
 *              credential-shaped string in the message (built here at run
 *              time): one `(file)` record whose message and detail carry the
 *              error, redacted.
 *   clean      a passing and a failing case: no record but theirs.
 *   grep       `dies` under --test-name-pattern that leaves its third case
 *              out: that case is never declared, so never cancelled.
 *   timeout    three 1.5 s cases with their own 10 s timeouts under a 2.5 s
 *              --test-timeout: on Node < 24, which bounds the FILE with it,
 *              the second is cancelled while running and the third before
 *              starting, as "file timeout". Node 24 applies --test-timeout
 *              to each test instead and cuts nothing: there all three pass,
 *              and nothing is reported cancelled.
 */

import { before, test } from "node:test";
import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import { existsSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { E2E_DIR, REPO_ROOT } from "../lib/paths.mjs";
import { nodeTestArgs } from "../lib/invocation.mjs";
import reporter, { CANCELLED_CODE, FILE_RECORD_NAME, isFileEvent } from "../lib/reporter.mjs";
import { LEAK_RE } from "../lib/http.mjs";
import { tempDir } from "./helpers/tmp.mjs";

const REPORTER = join(E2E_DIR, "lib", "reporter.mjs");
const NODE_MAJOR = Number(process.versions.node.split(".")[0]);
/** Node < 24 cuts a file at its --test-timeout; Node 24 applies it to each test (measured on 22.17 and 24.21). */
const FILE_BOUNDED = NODE_MAJOR < 24;

const DIES = `// fixture, generated by selftest/reporter-file-failure.test.mjs
import { test } from "node:test";
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
test("first", () => {});
test("dies", async (t) => {
  await t.test("child ok", () => {});
  await sleep(300);
  console.error("about to exit: e2e fixture");
  await sleep(100);
  process.exit(7);
});
test("never", () => {});
`;

const HOOK = `// fixture, generated by selftest/reporter-file-failure.test.mjs
import { after, test } from "node:test";
test("ok", () => {});
after(() => { throw new Error("after hook boom (e2e fixture)"); });
`;

// The token shape is assembled when the fixture runs, so no file holds it.
const LOAD = `// fixture, generated by selftest/reporter-file-failure.test.mjs
import { test } from "node:test";
const token = ["bsk", "_", "a".repeat(32), ".", "s".repeat(24)].join("");
throw new Error("load boom (e2e fixture) Authorization: Bearer " + token);
test("unreachable", () => {});
`;

const CLEAN = `// fixture, generated by selftest/reporter-file-failure.test.mjs
import { test } from "node:test";
test("passes", () => {});
test("fails on purpose", () => { throw new Error("an ordinary failure"); });
`;

const TIMEOUT = `// fixture, generated by selftest/reporter-file-failure.test.mjs
import { test } from "node:test";
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
test("t1", { timeout: 10_000 }, async () => { await sleep(1_500); });
test("t2", { timeout: 10_000 }, async () => { await sleep(1_500); });
test("t3", { timeout: 10_000 }, async () => { await sleep(1_500); });
`;

function childEnv() {
  const env = { ...process.env, E2E_SUITE: "functional", E2E_RUN_ID: "selftest-reporter-file" };
  delete env.NODE_TEST_CONTEXT; // a nested node --test that inherits it streams to us and ignores reporters
  return env;
}

/** One `node --test` over `file` with the real reporter; resolves {status, out, records}. */
function run(dir, name, src, { timeout = null, grep = null } = {}) {
  const file = join(dir, `${name}.spec.mjs`);
  writeFileSync(file, src);
  const resultsFile = join(dir, `${name}.results.jsonl`);
  return new Promise((resolve) => {
    const args = nodeTestArgs({ files: [file], resultsFile, reporter: REPORTER, concurrency: 1, timeout, grep });
    const child = spawn(process.execPath, args, { cwd: REPO_ROOT, env: childEnv(), stdio: ["ignore", "pipe", "pipe"], detached: true });
    let out = "";
    child.stdout.on("data", (c) => (out += c));
    child.stderr.on("data", (c) => (out += c));
    const killer = setTimeout(() => {
      try {
        process.kill(-child.pid, "SIGKILL");
      } catch {}
    }, 60_000);
    child.on("close", (status) => {
      clearTimeout(killer);
      const lines = existsSync(resultsFile) ? readFileSync(resultsFile, "utf8").split("\n").filter(Boolean) : [];
      // Records name the file as its process loaded it: the temp directory's real path.
      resolve({ file: realpathSync(file), status, out, records: lines.map((l) => JSON.parse(l)) });
    });
  });
}

const byPath = (r) => Object.fromEntries(r.records.map((x) => [x.path.join(" > "), x]));
const R = {};

before(async () => {
  const dir = tempDir("e2e-reporter-file-");
  const [dies, hook, load, clean, grep, timeout] = await Promise.all([
    run(dir, "dies", DIES),
    run(dir, "hook", HOOK),
    run(dir, "load", LOAD),
    run(dir, "clean", CLEAN),
    run(dir, "grep", DIES, { grep: "^(first|dies|child ok)$" }),
    run(dir, "timeout", TIMEOUT, { timeout: 2_500 }),
  ]);
  Object.assign(R, { dies, hook, load, clean, grep, timeout });
});

test("isFileEvent: the per-file wrapper by its given or absolute name, never a case", () => {
  assert.equal(isFileEvent({ file: "/x/a.spec.mjs", nesting: 0, name: "/x/a.spec.mjs" }), true);
  assert.equal(isFileEvent({ file: join(process.cwd(), "a.spec.mjs"), nesting: 0, name: "a.spec.mjs" }), true, "a relative argument resolves against the run's cwd");
  assert.equal(isFileEvent({ file: "/x/a.spec.mjs", nesting: 1, name: "/x/a.spec.mjs" }), false, "a subtest is never the file");
  assert.equal(isFileEvent({ file: "/x/a.spec.mjs", nesting: 0, name: "A14.1 a case" }), false);
  assert.equal(isFileEvent({ nesting: 0, name: "x" }), false, "no file, no file event");
});

/** The reporter over a synthetic event stream: its records. */
async function feed(events) {
  const out = [];
  for await (const line of reporter((async function* () {
    yield* events;
  })())) out.push(JSON.parse(line));
  return out;
}

test("NEGATIVE: a per-file wrapper that PASSES is never a record, and cancels nothing", async () => {
  const file = "/e2e-selftest/never-on-disk/a.spec.mjs";
  const ev = (type, name, extra = {}) => ({ type, data: { file, name, nesting: 0, ...extra } });
  const recs = await feed([
    ev("test:enqueue", file),
    ev("test:enqueue", "one"),
    ev("test:dequeue", "one"),
    ev("test:enqueue", "two"),
    ev("test:pass", "one", { details: { duration_ms: 1, type: "test" } }),
    ev("test:pass", file, { details: { duration_ms: 2, type: "test" } }),
  ]);
  assert.deepEqual(recs.map((r) => [r.name, r.status]), [["one", "pass"]], "only the case: a passing file declares nothing cancelled, even with a case it never ran");
});

test("a process that exits mid-case: the case running and the one after it are FAIL records, the subtest keeps its parent", () => {
  const r = R.dies;
  assert.notEqual(r.status, 0, "node --test exits non-zero");
  const recs = byPath(r);
  assert.deepEqual(Object.keys(recs).sort(), ["dies", "dies > child ok", "first", "never"], `records: ${JSON.stringify(r.records.map((x) => x.id))}`);
  assert.deepEqual([recs.first.status, recs["dies > child ok"].status], ["pass", "pass"]);
  assert.equal(recs["dies > child ok"].id, `${r.file}::dies > child ok`, "the subtest's id names its cancelled parent");
  const dies = recs.dies;
  assert.deepEqual([dies.status, dies.error.code, dies.cancelled.reason, dies.cancelled.started], ["fail", CANCELLED_CODE, "file-failed", true]);
  assert.equal(dies.error.message, "cancelled: the spec file failed (test failed) while this case ran");
  assert.equal(dies.id, `${r.file}::dies`);
  const never = recs.never;
  assert.deepEqual([never.status, never.error.code, never.cancelled.started], ["fail", CANCELLED_CODE, false]);
  assert.match(never.error.message, /^cancelled: the spec file failed \(test failed\) before this case started$/);
  assert.equal(r.records.filter((x) => x.name === FILE_RECORD_NAME).length, 0, "the cases carry the failure; no record of the file's own");
  for (const x of r.records) assert.deepEqual([x.suite, x.runId], ["functional", "selftest-reporter-file"]);
});

test("a top-level hook that fails after every case reported: one (file) record with its message", () => {
  const r = R.hook;
  assert.notEqual(r.status, 0);
  const recs = byPath(r);
  assert.deepEqual(Object.keys(recs).sort(), [FILE_RECORD_NAME, "ok"].sort(), `records: ${JSON.stringify(r.records.map((x) => x.id))}`);
  assert.equal(recs.ok.status, "pass");
  const f = recs[FILE_RECORD_NAME];
  assert.deepEqual([f.status, f.error.code, f.fileFailure.failureType, f.id], ["fail", CANCELLED_CODE, "hookFailed", `${r.file}::${FILE_RECORD_NAME}`]);
  assert.match(f.error.message, /^the spec file failed outside any case: after hook boom \(e2e fixture\)/);
});

test("a file that throws as it loads: one (file) record whose message carries the error, with credentials redacted", () => {
  const r = R.load;
  assert.notEqual(r.status, 0);
  assert.equal(r.records.length, 1, `records: ${JSON.stringify(r.records)}`);
  const f = r.records[0];
  assert.deepEqual([f.name, f.status, f.error.code], [FILE_RECORD_NAME, "fail", CANCELLED_CODE]);
  const text = `${f.error.message}\n${f.detail.join("\n")}`;
  assert.match(text, /load boom \(e2e fixture\)/, "what the file said is in the record, not only on stdout");
  assert.ok(f.detail.length > 0 && f.detail.length <= 30, `detail is capped: ${f.detail.length}`);
  assert.equal(LEAK_RE.test(JSON.stringify(f)), false, "no credential shape survives into the record");
  assert.match(text, /bsk_a{32}\.‹redacted›/, "the token is redacted, its prefix kept");
  assert.match(r.out, /bsk_a{32}\.s{24}/, "the fixture really printed the token: the redaction above is the reporter's");
});

test("NEGATIVE: an ordinary failing case makes no extra record, and the wrapper stays silent", () => {
  const r = R.clean;
  assert.notEqual(r.status, 0, "a failing case fails the run");
  assert.deepEqual(r.records.map((x) => [x.name, x.status, x.cancelled ?? null]).sort(), [["fails on purpose", "fail", null], ["passes", "pass", null]]);
});

test("a case --test-name-pattern left out is never declared, so never reported as cancelled", () => {
  const recs = byPath(R.grep);
  assert.deepEqual(Object.keys(recs).sort(), ["dies", "dies > child ok", "first"], `records: ${JSON.stringify(R.grep.records.map((x) => x.id))}`);
  assert.equal(recs.dies.cancelled.started, true);
});

test(FILE_BOUNDED ? "the file's --test-timeout: the case running is cancelled as \"file timeout\", the next before it starts" : "NEGATIVE: Node 24 does not bound the file with --test-timeout, and nothing is reported cancelled", () => {
  const r = R.timeout;
  const recs = byPath(r);
  assert.deepEqual(Object.keys(recs).sort(), ["t1", "t2", "t3"], `records: ${JSON.stringify(r.records.map((x) => x.id))}`);
  if (!FILE_BOUNDED) {
    // Each 1.5 s case is within its own 10 s; the 2.5 s applies per test here.
    assert.deepEqual([r.status, ...["t1", "t2", "t3"].map((n) => recs[n].status)], [0, "pass", "pass", "pass"], r.out.slice(-1500));
    return;
  }
  assert.notEqual(r.status, 0);
  assert.equal(recs.t1.status, "pass");
  assert.deepEqual([recs.t2.status, recs.t2.cancelled.reason, recs.t2.cancelled.started, recs.t2.error.failureType], ["fail", "file-timeout", true, "testTimeoutFailure"]);
  assert.equal(recs.t2.error.message, "cancelled: file timeout (test timed out after 2500ms) while this case ran");
  assert.deepEqual([recs.t3.status, recs.t3.cancelled.started], ["fail", false]);
  assert.equal(recs.t3.error.message, "cancelled: file timeout (test timed out after 2500ms) before this case started");
});
