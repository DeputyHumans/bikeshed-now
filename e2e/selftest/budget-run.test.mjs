// Self-test: under node --test, a file given its budget runs every healthy case, and a case without its own timeout keeps the case default instead of holding its file for the whole budget (SPEC §12).

/**
 * Generated fixture specs run through `node --test` with the argv run.mjs
 * builds (nodeTestArgs: `--test-timeout=<ms>` on the parent) and the real
 * scenario().
 *
 * WHAT --test-timeout BOUNDS depends on Node (measured, 4 × 1 s cases with
 * their own 5 s timeouts at --test-timeout=3500):
 *
 *   Node 22.17  the FILE: the parent cancels it at 3.5 s (pass 3, cancelled 1;
 *               the cases after that never run). A fixed tier timeout cut
 *               healthy cases, which is why run.mjs sizes it from the file's
 *               budget.
 *   Node 24.21  each TEST: the runner passes the flag down to the file's
 *               process, where it is the default timeout of every test with
 *               none of its own, and no file is cut (pass 4, cancelled 0).
 *
 * So on Node 24 a fixed tier timeout cancels nothing healthy. What goes wrong
 * without a per-case budget is the other half: run.mjs passes the FILE budget
 * (the sum of the file's case timeouts, up to 6× the tier default) as
 * --test-timeout, and a case with no timeout of its own inherits it. A case
 * that hangs then holds its file, and one of the tier's concurrency slots,
 * for the whole budget instead of its own bound. E2E_CASE_TIMEOUT_MS (the
 * tier default, which scenario() gives such a case) is what stops it at its
 * own bound, on either Node; the NEGATIVE control below runs the same file
 * without it and watches the hung case hold on to the full budget.
 */

import { after, before, test } from "node:test";
import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { E2E_DIR, OUT_DIR, REPO_ROOT } from "../lib/paths.mjs";
import { nodeTestArgs } from "../lib/invocation.mjs";
import { CASE_TIMEOUT_ENV, tierTimeouts } from "../lib/budget.mjs";
import { tempDir } from "./helpers/tmp.mjs";

const lib = (f) => pathToFileURL(join(E2E_DIR, "lib", f)).href;
const TIER_DEFAULT = 3_500;

const HEALTHY = `// fixture spec, generated by selftest/budget-run.test.mjs
import { scenario } from ${JSON.stringify(lib("test.mjs"))};
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
scenario("healthy 1", { timeoutMs: 5_000 }, async () => { await sleep(1_000); });
scenario("healthy 2", { timeoutMs: 5_000 }, async () => { await sleep(1_000); });
scenario("healthy 3", { timeoutMs: 5_000 }, async () => { await sleep(1_000); });
scenario("healthy 4", { timeoutMs: 5_000 }, async () => { await sleep(1_000); });
`;

// One case that never finishes and has no timeout of its own, then three healthy
// ones: tierTimeouts gives the file 3,500 + 3 × 5,000 = 18,500 ms.
const HANGS = `// fixture spec, generated by selftest/budget-run.test.mjs
import { scenario } from ${JSON.stringify(lib("test.mjs"))};
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
scenario("hangs, no timeout of its own", {}, async () => { await sleep(120_000); });
scenario("healthy after it 1", { timeoutMs: 5_000 }, async () => { await sleep(300); });
scenario("healthy after it 2", { timeoutMs: 5_000 }, async () => { await sleep(300); });
scenario("healthy after it 3", { timeoutMs: 5_000 }, async () => { await sleep(300); });
`;

const NO_OWN_TIMEOUT = `// fixture spec, generated by selftest/budget-run.test.mjs
import { scenario } from ${JSON.stringify(lib("test.mjs"))};
scenario("no timeout of its own", {}, async () => { await new Promise((r) => setTimeout(r, 3_000)); });
`;

function run(files, { timeout, env }) {
  return new Promise((resolve) => {
    const args = nodeTestArgs({ files, resultsFile: null, reporter: null, concurrency: 1, timeout });
    const child = spawn(process.execPath, args, { cwd: REPO_ROOT, env, stdio: ["ignore", "pipe", "pipe"], detached: true });
    let out = "";
    child.stdout.on("data", (c) => (out += c));
    child.stderr.on("data", (c) => (out += c));
    const killer = setTimeout(() => {
      try {
        process.kill(-child.pid, "SIGKILL");
      } catch {}
    }, 60_000);
    const t0 = Date.now();
    child.on("close", (status) => {
      clearTimeout(killer);
      const count = (k) => Number(new RegExp(`^ℹ ${k} (\\d+)$`, "m").exec(out)?.[1] ?? NaN);
      const timedOut = [...out.matchAll(/test timed out after (\d+)ms/g)].map((m) => Number(m[1]));
      resolve({ status, out, ms: Date.now() - t0, timedOut, pass: count("pass"), fail: count("fail"), cancelled: count("cancelled") });
    });
  });
}

let healthy;
let hangs;
let noOwn;
let runDir;
let budget;
let hangBudget;
const results = {};

before(async () => {
  const dir = tempDir("e2e-budget-run-");
  const runId = `selftest-budget-${process.pid}`;
  runDir = join(OUT_DIR, runId); // evidence goes only under e2e/.out
  mkdirSync(runDir, { recursive: true });
  const targetFile = join(dir, "target.json");
  writeFileSync(targetFile, JSON.stringify({ kind: "local", runId, runDir, origin: "http://127.0.0.1:9", projectId: "demo-bikeshed", capabilities: ["local"], stack: { ports: { hosting: 9 } } }));
  healthy = join(dir, "healthy.spec.mjs");
  hangs = join(dir, "hangs.spec.mjs");
  noOwn = join(dir, "no-own-timeout.spec.mjs");
  writeFileSync(healthy, HEALTHY);
  writeFileSync(hangs, HANGS);
  writeFileSync(noOwn, NO_OWN_TIMEOUT);
  const env = { ...process.env, E2E_TARGET: targetFile, E2E_RUN_ID: runId, E2E_SUITE: "functional" };
  delete env.NODE_TEST_CONTEXT; // a nested node --test that inherits it streams to us and ignores reporters
  delete env[CASE_TIMEOUT_ENV];
  delete env.E2E_INVOCATION_DIR;
  budget = tierTimeouts([healthy], { defaultMs: TIER_DEFAULT });
  hangBudget = tierTimeouts([hangs], { defaultMs: TIER_DEFAULT });
  const [withBudget, fixed, hangCaseDefault, hangInherited, caseDefault, inherited] = await Promise.all([
    run([healthy], { timeout: budget.fileTimeoutMs, env: { ...env, [CASE_TIMEOUT_ENV]: String(budget.caseTimeoutMs) } }),
    run([healthy], { timeout: TIER_DEFAULT, env }),
    // run.mjs's argv for the hanging file, with and without the per-case default.
    run([hangs], { timeout: hangBudget.fileTimeoutMs, env: { ...env, [CASE_TIMEOUT_ENV]: String(hangBudget.caseTimeoutMs) } }),
    run([hangs], { timeout: hangBudget.fileTimeoutMs, env }),
    run([noOwn], { timeout: 20_000, env: { ...env, [CASE_TIMEOUT_ENV]: "1000" } }),
    run([noOwn], { timeout: 20_000, env }),
  ]);
  Object.assign(results, { withBudget, fixed, hangCaseDefault, hangInherited, caseDefault, inherited });
});

after(() => {
  if (runDir) rmSync(runDir, { recursive: true, force: true });
});

test("tierTimeouts gives the healthy file the sum of its cases' own timeouts", () => {
  assert.deepEqual([budget.fileTimeoutMs, budget.caseTimeoutMs, budget.driver], [20_000, TIER_DEFAULT, healthy]);
});

test("at its budget, every healthy case runs and passes", () => {
  const r = results.withBudget;
  assert.deepEqual([r.pass, r.fail, r.cancelled, r.status], [4, 0, 0, 0], r.out.slice(-1500));
});

test("what --test-timeout bounds on this Node: Node 24 gives it to each test and cuts no file; Node 22 cut the file", (t) => {
  const r = results.fixed;
  const major = Number(process.versions.node.split(".")[0]);
  if (major >= 24) {
    assert.deepEqual([r.pass, r.cancelled, r.status], [4, 0, 0], `at a fixed ${TIER_DEFAULT} ms --test-timeout, Node ${process.versions.node} still runs every healthy case with a timeout of its own: ${r.out.slice(-1500)}`);
  } else if (major <= 22) {
    assert.ok(r.pass >= 1 && r.pass < 4 && r.cancelled >= 1 && r.timedOut.includes(TIER_DEFAULT), `Node ${process.versions.node} cuts the file at ${TIER_DEFAULT} ms: ${r.out.slice(-1500)}`);
  } else {
    t.skip(`Node ${process.versions.node}: never measured (22.17 cuts the file, 24.21 does not)`);
  }
});

test("the hanging file's budget is the per-case default for the hung case plus the healthy cases' own timeouts", () => {
  assert.deepEqual([hangBudget.fileTimeoutMs, hangBudget.caseTimeoutMs], [TIER_DEFAULT + 3 * 5_000, TIER_DEFAULT]);
});

test("with E2E_CASE_TIMEOUT_MS, a hung case without a timeout of its own is cut at the case default and the cases after it run", () => {
  const r = results.hangCaseDefault;
  assert.deepEqual(r.timedOut, [TIER_DEFAULT], `cut once, at the case default: ${r.out.slice(-1500)}`);
  assert.equal(r.pass, 3, `the three healthy cases after it ran and passed: ${r.out.slice(-1500)}`);
  assert.ok(r.ms < hangBudget.fileTimeoutMs, `the file was done in ${r.ms} ms, well inside its ${hangBudget.fileTimeoutMs} ms budget`);
});

test("NEGATIVE: without a per-case budget, the hung case inherits the FILE budget and holds its file for all of it", () => {
  const r = results.hangInherited;
  // Node 24: the case's own timeout is the --test-timeout default. Node 22:
  // the file is cut at it. Either way the hang is held for the whole budget.
  assert.ok(r.timedOut.includes(hangBudget.fileTimeoutMs) && !r.timedOut.includes(TIER_DEFAULT), `expected the hung case to be cut only at the file's ${hangBudget.fileTimeoutMs} ms budget, never at the ${TIER_DEFAULT} ms case default (timed out after ${JSON.stringify(r.timedOut)} ms): ${r.out.slice(-1500)}`);
  assert.ok(r.ms >= hangBudget.fileTimeoutMs, `the file was held ${r.ms} ms, at least its ${hangBudget.fileTimeoutMs} ms budget`);
});

test("a case with no timeoutMs of its own is held to E2E_CASE_TIMEOUT_MS, not to the file's budget", () => {
  const r = results.caseDefault;
  // node:test counts a case stopped by its own timeout as cancelled.
  assert.deepEqual([r.pass, r.fail + r.cancelled], [0, 1], r.out.slice(-1500));
  assert.match(r.out, /test timed out after 1000ms/, "node:test reports the case's own timeout");
});

test("NEGATIVE: without E2E_CASE_TIMEOUT_MS the same case inherits the file's timeout and passes", () => {
  const r = results.inherited;
  assert.deepEqual([r.pass, r.fail], [1, 0], r.out.slice(-1500));
});
