  const A = add("2026-10-13T10:00:00Z", [seen("race [N=2] #1", "2026-10-13T10:01:00Z"), nr("race [N=2] #2", "2026-10-13T10:02:00Z"), rec("flip [N=2] #1", "fail", "2026-10-13T10:03:00Z", { error: { message: "other oracle" } }), rec("gone", "pass", "2026-10-13T10:04:00Z"), seen("seen twice", "2026-10-13T10:05:00Z")]);
