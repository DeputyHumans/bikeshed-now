test("mergeRun writes results.json and summary.md; classify and compare work by stable id, through run.mjs too", () => {
  const { results: merged, summary } = mergeRun(inv.dir);
  assert.deepEqual(summary.counts, { pass: 6, fail: 9, inconclusive: 1, todo: 3, skip: 3 });
  assert.equal(summary.unexpectedPasses.length, 1);
  assert.equal(summary.unclassified.length, 9);
  assert.deepEqual(summary.inconclusive.map((x) => x.reason), ["fire spread 22.0 ms > 15 ms"]);
  const md = readFileSync(join(inv.dir, "summary.md"), "utf8");
  assert.match(md, /## Failures/);
  assert.match(md, /## Inconclusive/);
  assert.match(md, /\*\*passed unexpectedly\*\*/);
  assert.equal(merged.cases.length, 22);
  assert.equal(merged.invocation.id, inv.id, "results.json names its invocation");
  assert.ok(!existsSync(join(runDir, "results.json")), "nothing is merged at the run level");

  const c = classify(runId, "plain failure", "H", "fixture failure on purpose");
  assert.equal(c.class, "H");
  assert.throws(() => classify(inv.dir, "plain failure", "X", "bad class"), /class must be one of/);
  assert.throws(() => classify(inv.dir, "a", "H", "ambiguous"), /cases match/);
  const again = JSON.parse(readFileSync(join(inv.dir, "results.json"), "utf8"));
  assert.equal(again.cases.find((r) => r.name === "plain failure").classification.class, "H");

  // Invocation B: alpha regresses, the plain failure is fixed, one passing
  // case disappears, one passing case is skipped and one becomes INCONCLUSIVE.
  const b = `${runDir}-b`;
  cpSync(inv.dir, b, { recursive: true });
  const lines = readFileSync(join(b, "results-functional.jsonl"), "utf8").trim().split("\n").map((l) => JSON.parse(l));
  const flipped = lines
    .filter((r) => r.name !== "trials [N=2] #2")
    .map((r) =>
      r.id === results["alpha [N=2]"].id ? { ...r, status: "fail" }
      : r.name === "plain failure" ? { ...r, status: "pass", error: null }
      : r.name === "trials [N=2] #1" ? { ...r, status: "skip", skipReason: "needs mailpit" }
      : r.name === "in a subtest" ? { ...r, status: "inconclusive", inconclusive: "spread 30 ms" }
      : r,
    );
  writeFileSync(join(b, "results-functional.jsonl"), flipped.map((r) => JSON.stringify(r)).join("\n") + "\n");
  rmSync(join(b, "results.json"));
  const cmp = compareRuns(inv.dir, b);
  assert.deepEqual(cmp.regressions.map((x) => x.id.split("::")[1]), ["alpha [N=2]"]);
  assert.deepEqual(cmp.fixed.map((x) => x.id.split("::")[1]), ["plain failure"]);
  assert.deepEqual(cmp.lost.map((x) => [x.id.split("::")[1], x.to]).sort(), [["in a subtest", "inconclusive"], ["trials [N=2] #1", "skip"], ["trials [N=2] #2", "absent"]], "a PASS that is gone, skipped or inconclusive is LOST");

  // A case B's own recorded selection left out is filtered, not lost.
  const bMeta = JSON.parse(readFileSync(join(b, "invocation.json"), "utf8"));
  writeFileSync(join(b, "invocation.json"), JSON.stringify({ ...bMeta, grep: "^(?!trials).*" }));
  rmSync(join(b, "results.json"), { force: true });
  const filtered = compareRuns(inv.dir, b);
  assert.ok(filtered.filtered.some((x) => x.id.endsWith("trials [N=2] #2")), JSON.stringify(filtered.filtered));
  assert.ok(!filtered.lost.some((x) => x.id.endsWith("trials [N=2] #2")));
  writeFileSync(join(b, "invocation.json"), JSON.stringify(bMeta));
  rmSync(join(b, "results.json"), { force: true });

  const cli = spawnSync(process.execPath, [join(E2E_DIR, "run.mjs"), "compare", inv.dir, b], { encoding: "utf8", env: childEnv() });
  assert.equal(cli.status, 1, "run.mjs compare exits 1 on a PASS → FAIL");
  assert.match(cli.stdout, /\| .*alpha \[N=2\] \| regression \| pass \| fail \|/);
  assert.match(cli.stdout, /\| .*trials \[N=2\] #2 \| lost \| pass \| absent \|/);

  // Only a lost pass, no regression: still exit 1.
  const c2 = `${runDir}-c`;
  cpSync(inv.dir, c2, { recursive: true });
  const kept = readFileSync(join(c2, "results-functional.jsonl"), "utf8").trim().split("\n").filter((l) => !JSON.parse(l).name.startsWith("trials [N=2] #2"));
  writeFileSync(join(c2, "results-functional.jsonl"), kept.join("\n") + "\n");
  rmSync(join(c2, "results.json"));
  const onlyLost = spawnSync(process.execPath, [join(E2E_DIR, "run.mjs"), "compare", inv.dir, c2], { encoding: "utf8", env: childEnv() });
  assert.equal(onlyLost.status, 1, `NEGATIVE: a pass that disappeared fails compare even with no PASS → FAIL\n${onlyLost.stdout}`);
  assert.match(onlyLost.stdout, /0 PASS → FAIL, 1 PASS lost/);

  const rep = spawnSync(process.execPath, [join(E2E_DIR, "run.mjs"), "report", `${runId}/${inv.id}`], { encoding: "utf8", env: childEnv() });
  assert.equal(rep.status, 0, rep.stderr);
  assert.match(rep.stdout, /22 cases: 6 pass, 9 fail, 1 inconclusive, 3 todo \(known defects\), 3 skip/);
  const cls = spawnSync(process.execPath, [join(E2E_DIR, "run.mjs"), "classify", runId, "::breach", "E", "made", "on", "purpose"], { encoding: "utf8", env: childEnv() });
  assert.equal(cls.status, 0, cls.stderr);
  assert.equal(JSON.parse(cls.stdout).note, "made on purpose");
  assert.ok(existsSync(join(inv.dir, "classifications.json")));
});
