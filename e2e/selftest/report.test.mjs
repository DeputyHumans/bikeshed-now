test("statuses: pass, skip with reasons, todo with its outcome, fail with error and evidence", () => {
  assert.equal(results["alpha [N=2]"].status, "pass");
  assert.equal(results["alpha [N=2]"].n, 2);
  assert.equal(results["alpha [N=5]"].status, "skip");
  assert.equal(results["alpha [N=5]"].skipReason, "N=5 not selected (--n 2)");
  assert.equal(results["prod only"].skipReason, "tier: runs on prod, not local");
  assert.match(results["needs a capability"].skipReason, /^needs no-such-capability/);
  assert.equal(results["known S3"].status, "todo");
  assert.equal(results["known S3"].outcome, "failed-as-expected");
  assert.equal(results["known S3"].todo, "known defect S3");
  assert.equal(results["known S9 fixed"].outcome, "passed-unexpectedly", "a fixed known defect is VISIBLE");
  assert.deepEqual([results["trials [N=2] #1"].trial, results["trials [N=2] #2"].trial], [1, 2]);
  const f = results["plain failure"];
  assert.equal(f.status, "fail");
  assert.equal(f.error.message, "boom");
  assert.ok(f.evidenceDir, "the evidence dir is attached to the failing case");
});

test("a known defect is TODO only when its own oracle fails; a breach, a missing precondition or a sync timeout FAILS", () => {
  const status = (name) => [results[name].status, results[name].outcome];
  assert.deepEqual(status("known S3"), ["todo", "failed-as-expected"], "an assertion in the body is the defect's oracle");
  assert.deepEqual(status("known S3, its eventually-oracle wrapped"), ["todo", "failed-as-expected"], "ctx.oracle() marks a non-assertion oracle");
  assert.deepEqual(status("known S3, but an isolation breach"), ["fail", null]);
  assert.match(results["known S3, but an isolation breach"].error.message, /isolation breach: 1 request/);
  assert.deepEqual(status("known S3, but its precondition is missing"), ["fail", null]);
  assert.equal(results["known S3, but its precondition is missing"].error.code, "E2E_PRECONDITION");
  assert.deepEqual(status("known S3, but a sync timeout"), ["fail", null]);
  assert.equal(results["known S3, but a sync timeout"].error.code, "E2E_SYNC_TIMEOUT");
});

test("INCONCLUSIVE is its own outcome, with its reason and evidence — and a breach still FAILS", () => {
  const r = results.inconclusive;
  assert.equal(r.status, "inconclusive");
  assert.equal(r.inconclusive, "fire spread 22.0 ms > 15 ms");
  assert.equal(r.skipReason, null);
  assert.ok(r.evidenceDir, "an inconclusive case leaves evidence");
  assert.match(readFileSync(join(REPO_ROOT, r.evidenceDir, "steps.md"), "utf8"), /spread measured/);
  const b = results["inconclusive, but an isolation breach"];
  assert.equal(b.status, "fail");
  assert.match(b.error.message, /isolation breach/);
});

test("a timeout keeps its evidence: the error, the steps, the user's screenshot; the late body's request stays its own", async () => {
  const h = resultsHang["hangs in a browser"];
  assert.equal(h.status, "fail");
  assert.ok(h.evidenceDir, "the timed-out case names its evidence directory");
  const dir = join(REPO_ROOT, h.evidenceDir);
  assert.match(readFileSync(join(dir, "error.txt"), "utf8"), /timed out after 2500 ms/);
  assert.match(readFileSync(join(dir, "steps.md"), "utf8"), /about to hang in page\.evaluate/);
  for (let i = 0; i < 50 && !existsSync(join(dir, "screenshot-u1.png")); i++) await new Promise((r) => setTimeout(r, 100));
  assert.ok(existsSync(join(dir, "screenshot-u1.png")), `screenshot of the hung page in ${readdirSync(dir).join(", ")}`);
  assert.match(readFileSync(join(dir, "http.jsonl"), "utf8"), /late-from-the-hung-case/, "the late request is in the hung case's own evidence");

  const n = resultsHang["after the hang"];
  assert.equal(n.status, "fail");
  const next = readFileSync(join(REPO_ROOT, n.evidenceDir, "http.jsonl"), "utf8");
  assert.match(next, /from-the-next-case/, "the next case's own request, made without an explicit sink, is in its evidence");
  assert.doesNotMatch(next, /late-from-the-hung-case/, "NEGATIVE: the hung case's late request did not leak into the next case");

  assert.equal(resultsHang["never settles"].status, "fail", "a body that never settles times out, and the process still ends");
});

test("evidence of a failure: steps with the rerun command, the error, attachments — all redacted", () => {
  const dir = join(REPO_ROOT, results["plain failure"].evidenceDir);
  const steps = readFileSync(join(dir, "steps.md"), "utf8");
  assert.match(steps, /about to fail/);
  assert.match(steps, /node e2e\/run\.mjs run --attach selftest-rep-\d+ .*--grep 'plain failure'/);
  assert.doesNotMatch(steps, /bsk_abcdefghijklmnop/, "a token shape is redacted in steps");
  assert.match(readFileSync(join(dir, "error.txt"), "utf8"), /boom/);
  const probe = JSON.parse(readFileSync(join(dir, "probe.json"), "utf8"));
  assert.deepEqual(probe, { password: "<redacted:7>", ok: 1 });
  assert.equal(results["alpha [N=2]"].evidenceDir, null, "a passing case leaves no evidence directory");
});

