/**
 * Runs generated fixture specs through `node --test` with the real reporter
 * and the argv run.mjs builds (nodeTestArgs), inside an invocation directory
 * made the way run.mjs makes it, then checks every record. Cases drive a real
 * browser into a foreign loopback port, so they also prove a breach FAILS a
 * scenario — one that otherwise passed, a known defect's, an INCONCLUSIVE
 * one. A third spec times out in a browser and then never settles, which
 * proves evidence on a timeout, per-case HTTP evidence, and force-exit.
 * Needs Chrome.
 */

