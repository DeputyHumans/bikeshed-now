// Self-test: a case with N >= 10 on a local stack waits for room for its browsers and the stack's growth before its body runs, and ends INCONCLUSIVE when the room never comes (SPEC §12).

/**
 * A generated fixture spec with one scenario at N = 2 and N = 10, run through
 * `node --test` with the real scenario() against a stand-in local target.
 * E2E_STACK_PEER_MB is set far ABOVE its default (tightening it, never
 * loosening) so that no machine has the room, and E2E_POOL_WAIT_MS to 0 so
 * the wait ends at once: the N=10 case must end INCONCLUSIVE without running
 * its body, while the N=2 case, which only the pool's own gate guards, runs.
 */

import { after, test } from "node:test";
import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { E2E_DIR, OUT_DIR, REPO_ROOT } from "../lib/paths.mjs";
import { CASE_TIMEOUT_ENV } from "../lib/budget.mjs";
import { tempDir } from "./helpers/tmp.mjs";

const lib = (f) => pathToFileURL(join(E2E_DIR, "lib", f)).href;
const dir = tempDir("e2e-live-reserve-");
const runId = `selftest-reserve-${process.pid}`;
const runDir = join(OUT_DIR, runId);
after(() => {
  rmSync(dir, { recursive: true, force: true });
  rmSync(runDir, { recursive: true, force: true });
});

function run(file, env) {
  return new Promise((resolve) => {
    const child = spawn(process.execPath, ["--test", "--test-reporter=spec", "--test-concurrency=1", file], { cwd: REPO_ROOT, env, stdio: ["ignore", "pipe", "pipe"], detached: true });
    let out = "";
    child.stdout.on("data", (c) => (out += c));
    child.stderr.on("data", (c) => (out += c));
    const killer = setTimeout(() => {
      try {
        process.kill(-child.pid, "SIGKILL");
      } catch {}
    }, 60_000);
    child.on("close", (status) => {
      clearTimeout(killer);
      resolve({ status, out });
    });
  });
}

test("N=10 on a local stack with no room for the browsers and the stack's growth: INCONCLUSIVE before the body; N=2 runs", { timeout: 90_000 }, async () => {
  mkdirSync(runDir, { recursive: true });
  const marks = join(dir, "bodies");
  mkdirSync(marks, { recursive: true });
  const spec = join(dir, "wide.spec.mjs");
  writeFileSync(spec, `// fixture spec, generated by selftest/live-reserve.test.mjs
import { writeFileSync } from "node:fs";
import { scenario } from ${JSON.stringify(lib("test.mjs"))};
scenario("wide", { n: [2, 10], trials: 1, timeoutMs: 30_000 }, async (ctx) => {
  writeFileSync(${JSON.stringify(marks)} + "/n" + ctx.n, "ran");
});
`);
  const targetFile = join(dir, "target.json");
  writeFileSync(targetFile, JSON.stringify({ kind: "local", runId, runDir, origin: "http://127.0.0.1:9", projectId: "demo-bikeshed", capabilities: ["local"], stack: { ports: { hosting: 9 } } }));
  const env = { ...process.env, E2E_TARGET: targetFile, E2E_RUN_ID: runId, E2E_SUITE: "functional", E2E_STACK_PEER_MB: "100000000", E2E_POOL_WAIT_MS: "0" };
  delete env.NODE_TEST_CONTEXT;
  delete env[CASE_TIMEOUT_ENV];
  delete env.E2E_INVOCATION_DIR;
  delete env.E2E_N;
  delete env.E2E_TRIALS;
  const r = await run(spec, env);
  const ran = existsSync(marks) ? readdirSync(marks).sort() : [];
  assert.deepEqual(ran, ["n2"], `only the N=2 body ran:\n${r.out}`);
  assert.match(r.out, /outcome=inconclusive:.*N=10 needs [\d.]+ GB available \(2 GB \+ 10 × 600 MB for the browsers, 10 × 100000000 MB for the stack's growth\)/, r.out);
  assert.match(r.out, /✔ wide \[N=2\]/);
});
