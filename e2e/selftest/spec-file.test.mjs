// Self-test: a spec file outside e2e/specs runs as a spec does, its invocation stays out of the run's merged view, and run.mjs --spec-file refuses a file it cannot run as written (SPEC §12).

/**
 * The checks run on files in temporary directories (and one under e2e/.out).
 * The last tests run a generated scratch spec through `node --test` with the
 * argv and reporter run.mjs uses, into a scratch invocation, and spawn
 * run.mjs itself only for refusals. Each spawn names an --attach id no stack
 * has, and sets HOME to an empty temporary directory, so that even a broken
 * run.mjs that got past its checks would find no stack to attach to and
 * nothing of this machine's to reap.
 */

import { after, before, test } from "node:test";
import assert from "node:assert/strict";
import { spawn, spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, realpathSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { isAbsolute, join, relative } from "node:path";
import { pathToFileURL } from "node:url";
import { E2E_DIR, OUT_DIR, REPO_ROOT, SPECS_DIR } from "../lib/paths.mjs";
import { INVOCATIONS_DIR, SCRATCH_INVOCATIONS_DIR, createInvocation, nodeTestArgs } from "../lib/invocation.mjs";
import { SPEC_FILE_SUITES, absoluteLibImports, checkSpecFile, specFilePlan, specImports } from "../lib/specfile.mjs";
import { listInvocations, mergeInvocations, mergeRun, runDirOf } from "../lib/report.mjs";
import { rerunCommand } from "../lib/test.mjs";
import { tempDir } from "./helpers/tmp.mjs";

const LIB_URL = pathToFileURL(join(E2E_DIR, "lib")).href;
const runId = `selftest-specfile-${process.pid}`;
const NO_STACK = "2610101200-zzzz"; // a run id no stack has

/** A spec as it is written in e2e/specs/functional/: lib imports are ../../lib/. */
const SPEC_SOURCE = `// fixture spec, generated by selftest/spec-file.test.mjs
import assert from "node:assert/strict";
import { scenario } from "../../lib/test.mjs";
// import { nothing } from "../../lib/commented.mjs";
const note = 'from "../../lib/in-a-string.mjs"';
scenario("SF.1 a scratch case that passes", { timeoutMs: 20_000 }, async (ctx) => {
  ctx.step("the copy runs this harness's scenario()");
  const { evidenceRoot } = await import("../../lib/invocation.mjs");
  assert.equal(evidenceRoot(ctx.target), process.env.E2E_INVOCATION_DIR);
  assert.ok(note.length > 0);
});
scenario("SF.2 a scratch case the mutation turns red", { timeoutMs: 20_000 }, async (ctx) => {
  ctx.step("the planted bug");
  assert.equal(1 + 1, 3, "the mutant's oracle fails");
});
`;

let dir;
let runDir;
let good;
let goodReal; // what node --test, and so a case's id, calls it
let outFile;

before(() => {
  dir = tempDir("e2e-specfile-");
  runDir = join(OUT_DIR, runId);
  mkdirSync(runDir, { recursive: true });
  good = join(dir, "m1-good.spec.mjs");
  writeFileSync(good, absoluteLibImports(SPEC_SOURCE));
  goodReal = realpathSync(good);
});

after(() => {
  rmSync(runDir, { recursive: true, force: true });
  if (outFile) rmSync(join(OUT_DIR, `selftest-specfile-src-${process.pid}`), { recursive: true, force: true });
});

const refused = (fn, re) => assert.throws(fn, (e) => e.code === "E2E_SPEC_FILE" && re.test(e.message), String(re));

test("specImports: static, side-effect, re-export and dynamic imports, never one in a comment or a string", () => {
  const src = [
    'import a from "./a.mjs";',
    "import { b,",
    "  c } from '../b.mjs';",
    'import "./side.mjs";',
    'export { d } from "./d.mjs";',
    'export * from "node:path";',
    'const e = await import("./e.mjs");',
    "const f = await import(`./f-${x}.mjs`);",
    '// import g from "./g.mjs";',
    '/* import h from "./h.mjs"; */',
    'const s = "import i from \\"./i.mjs\\"";',
    "const re = /from \"x\"/;",
    "const t = Array.from(\"abc\");",
  ].join("\n");
  assert.deepEqual(specImports(src).map((i) => [i.specifier, i.line, i.dynamic]), [
    ["./a.mjs", 1, false],
    ["../b.mjs", 3, false],
    ["./side.mjs", 4, false],
    ["./d.mjs", 5, false],
    ["node:path", 6, false],
    ["./e.mjs", 7, true],
  ]);
});

test("absoluteLibImports: a spec's ../../lib/ imports become this harness's lib by file URL, and nothing else changes", () => {
  const out = absoluteLibImports(SPEC_SOURCE);
  assert.ok(out.includes(`import { scenario } from "${LIB_URL}/test.mjs";`));
  assert.ok(out.includes(`await import("${LIB_URL}/invocation.mjs")`), "a dynamic import too");
  assert.ok(out.includes('// import { nothing } from "../../lib/commented.mjs";'), "a comment is left alone");
  assert.ok(out.includes(`const note = 'from "../../lib/in-a-string.mjs"';`), "a string is left alone");
  assert.ok(out.includes('import assert from "node:assert/strict";'));
  assert.equal(out.split("\n").length, SPEC_SOURCE.split("\n").length, "the same lines");
  assert.equal(absoluteLibImports(out), out, "idempotent");
});

test("checkSpecFile: a copy in a scratch directory, importing this lib by URL or by path, builtins, packages and its own helpers", () => {
  const helper = join(dir, "helper.mjs");
  writeFileSync(helper, "export const h = 1;\n");
  const f = join(dir, "m2-forms.spec.mjs");
  writeFileSync(f, [`import { scenario } from "${LIB_URL}/test.mjs";`, `import { treeConstant } from ${JSON.stringify(join(E2E_DIR, "lib", "target.mjs"))};`, 'import { h } from "./helper.mjs";', 'import { chromium } from "playwright-core";', 'import { test } from "node:test";'].join("\n") + "\n");
  const r = checkSpecFile(f);
  assert.equal(r.file, f);
  assert.deepEqual(r.imports.map((i) => i.specifier), [`${LIB_URL}/test.mjs`, join(E2E_DIR, "lib", "target.mjs"), "./helper.mjs", "playwright-core", "node:test"]);
  assert.equal(r.imports[2].resolved.endsWith("helper.mjs"), true);
  assert.deepEqual(r.imports.slice(3).map((i) => i.resolved), [null, null], "builtins and packages are not resolved");
  assert.deepEqual(checkSpecFile(good).imports.filter((i) => i.resolved).map((i) => relative(E2E_DIR, i.resolved)), ["lib/test.mjs", "lib/invocation.mjs"]);
  // Under e2e/.out (gitignored) is allowed.
  const outDir = join(OUT_DIR, `selftest-specfile-src-${process.pid}`);
  mkdirSync(outDir, { recursive: true });
  outFile = join(outDir, "m3.spec.mjs");
  writeFileSync(outFile, absoluteLibImports(SPEC_SOURCE));
  assert.equal(checkSpecFile(outFile).file, outFile);
});

test("NEGATIVE: checkSpecFile refuses a path it cannot run as written, or one in the tracked tree", () => {
  refused(() => checkSpecFile("e2e/specs/functional/a18-stats.spec.mjs"), /not an absolute path/);
  refused(() => checkSpecFile(`${dir}/x/../m1-good.spec.mjs`), /not resolved/);
  refused(() => checkSpecFile(join(SPECS_DIR, "functional", "a18-stats.spec.mjs")), /is in e2e\/specs\/: run it with --spec e2e\/specs\/functional\/a18-stats\.spec\.mjs/);
  refused(() => checkSpecFile(join(E2E_DIR, "lib", "m1.spec.mjs")), /in this checkout outside e2e\/\.out\/: a scratch copy stays out of the tracked tree/);
  refused(() => checkSpecFile(join(REPO_ROOT, "m1.spec.mjs")), /outside e2e\/\.out\//);
  refused(() => checkSpecFile(join(dir, "missing.spec.mjs")), /no such file/);
  mkdirSync(join(dir, "adir.spec.mjs"), { recursive: true });
  refused(() => checkSpecFile(join(dir, "adir.spec.mjs")), /not a regular file/);
  writeFileSync(join(dir, "m4.spec.js"), absoluteLibImports(SPEC_SOURCE));
  refused(() => checkSpecFile(join(dir, "m4.spec.js")), /not a \.mjs file/);
  // A copy that kept the spec's relative imports.
  writeFileSync(join(dir, "m5-relative.spec.mjs"), SPEC_SOURCE);
  refused(() => checkSpecFile(join(dir, "m5-relative.spec.mjs")), /m5-relative\.spec\.mjs:3 imports "\.\.\/\.\.\/lib\/test\.mjs", which is no file .*absoluteLibImports/);
  // Another harness's lib.
  const other = join(dir, "other", "e2e", "lib");
  mkdirSync(other, { recursive: true });
  writeFileSync(join(other, "test.mjs"), "export const scenario = () => {};\n");
  writeFileSync(join(dir, "m6-other.spec.mjs"), `import { scenario } from ${JSON.stringify(pathToFileURL(join(other, "test.mjs")).href)};\n`);
  refused(() => checkSpecFile(join(dir, "m6-other.spec.mjs")), /from an e2e\/lib\/ that is not this harness's/);
  writeFileSync(join(dir, "m7-dyn.spec.mjs"), 'await import("./nowhere.mjs");\n');
  refused(() => checkSpecFile(join(dir, "m7-dyn.spec.mjs")), /imports "\.\/nowhere\.mjs", which is no file/);
  // A link from a scratch directory to a tracked spec is that spec.
  symlinkSync(join(SPECS_DIR, "smoke", "canary.spec.mjs"), join(dir, "m8-link.spec.mjs"));
  refused(() => checkSpecFile(join(dir, "m8-link.spec.mjs")), /is in e2e\/specs\//);
});

test("specFilePlan: null without --spec-file; one tier and checked files with it; refusals before any stack", () => {
  assert.equal(specFilePlan({}), null);
  assert.equal(specFilePlan({ specFiles: [], attach: NO_STACK }), null);
  assert.deepEqual(specFilePlan({ specFiles: [good], attach: NO_STACK }), { tier: "functional", files: [goodReal] }, "the real path, as node --test names the file");
  assert.deepEqual(specFilePlan({ specFiles: [good], attach: NO_STACK, suite: "concurrency" }), { tier: "concurrency", files: [goodReal] });
  assert.deepEqual(SPEC_FILE_SUITES, ["functional", "concurrency"]);
  refused(() => specFilePlan({ specFiles: [good] }), /add --attach <runId>/);
  refused(() => specFilePlan({ specFiles: [good], attach: NO_STACK, spec: ["a18"] }), /--spec-file and --spec do not mix/);
  refused(() => specFilePlan({ specFiles: [good], attach: NO_STACK, suite: "smoke" }), /runs in one tier: --suite functional or concurrency, not smoke/);
  refused(() => specFilePlan({ specFiles: [good], attach: NO_STACK, suite: "all" }), /not all/);
  refused(() => specFilePlan({ specFiles: [good, good], attach: NO_STACK }), /named twice/);
  symlinkSync(good, join(dir, "m9-alias.spec.mjs"));
  refused(() => specFilePlan({ specFiles: [good, join(dir, "m9-alias.spec.mjs")], attach: NO_STACK }), /m9-alias\.spec\.mjs is named twice \(as /);
  refused(() => specFilePlan({ specFiles: [join(dir, "m5-relative.spec.mjs")], attach: NO_STACK }), /which is no file/);
});

test("rerunCommand: --spec for a spec in e2e/specs, --spec-file for any other file", () => {
  const inTree = join(SPECS_DIR, "functional", "a18-stats.spec.mjs");
  assert.equal(rerunCommand("2610102144-wr3h", inTree, "A18.5 (x) it's"), "node e2e/run.mjs run --attach 2610102144-wr3h --spec e2e/specs/functional/a18-stats.spec.mjs --grep 'A18\\.5 \\(x\\) it'\\''s'");
  assert.equal(rerunCommand("2610102144-wr3h", goodReal, "SF.2 y"), `node e2e/run.mjs run --attach 2610102144-wr3h --spec-file ${goodReal} --grep 'SF\\.2 y'`);
  assert.equal(rerunCommand("2610102144-wr3h", join(E2E_DIR, "selftest", "x.test.mjs"), "z"), `node e2e/run.mjs run --attach 2610102144-wr3h --spec-file ${join(E2E_DIR, "selftest", "x.test.mjs")} --grep 'z'`);
  assert.equal(rerunCommand("2610102144-wr3h", null, "z"), "node e2e/run.mjs run --attach 2610102144-wr3h --grep 'z'");
});

test("createInvocation under scratch/: beside invocations/, and in no listing of them", () => {
  const scratch = createInvocation(runDir, { probe: true }, { under: SCRATCH_INVOCATIONS_DIR });
  assert.equal(scratch.dir, join(runDir, SCRATCH_INVOCATIONS_DIR, scratch.id));
  assert.ok(existsSync(join(scratch.dir, "invocation.json")));
  assert.deepEqual(listInvocations(runDir), [], "not an invocation of the run");
  const plain = createInvocation(runDir, { probe: true });
  assert.equal(plain.dir, join(runDir, INVOCATIONS_DIR, plain.id), "the default is unchanged");
  assert.deepEqual(listInvocations(runDir), [plain.id]);
  assert.throws(() => createInvocation(runDir, {}, { under: "../elsewhere" }), /under is "invocations" or "scratch"/);
  rmSync(join(runDir, SCRATCH_INVOCATIONS_DIR), { recursive: true, force: true });
  rmSync(join(runDir, INVOCATIONS_DIR), { recursive: true, force: true });
});

function nodeTest(files, env) {
  return new Promise((resolve) => {
    const child = spawn(process.execPath, nodeTestArgs({ files, resultsFile: env.RESULTS, reporter: "./e2e/lib/reporter.mjs", concurrency: 1, timeout: 60_000 }), { cwd: REPO_ROOT, env, stdio: ["ignore", "pipe", "pipe"], detached: true });
    let out = "";
    child.stdout.on("data", (c) => (out += c));
    child.stderr.on("data", (c) => (out += c));
    const killer = setTimeout(() => {
      try {
        process.kill(-child.pid, "SIGKILL");
      } catch {}
    }, 90_000);
    child.on("close", (status) => {
      clearTimeout(killer);
      resolve({ status, out });
    });
  });
}

test("a scratch copy runs as a spec does: its ids name the copy, its evidence and rerun are the scratch invocation's, and the run's merged view leaves it out", async () => {
  const targetFile = join(dir, "target.json");
  writeFileSync(targetFile, JSON.stringify({ kind: "local", runId, runDir, origin: "http://127.0.0.1:9", projectId: "demo-bikeshed", capabilities: ["local"], stack: { ports: { hosting: 9 } } }));
  const scratch = createInvocation(runDir, { suite: "functional", scratch: true, specFile: [goodReal] }, { under: SCRATCH_INVOCATIONS_DIR });
  const env = { ...process.env, E2E_TARGET: targetFile, E2E_RUN_ID: runId, E2E_SUITE: "functional", E2E_INVOCATION_DIR: scratch.dir, RESULTS: join(scratch.dir, "results-functional.jsonl") };
  delete env.NODE_TEST_CONTEXT; // a nested node --test that inherits it streams to us and ignores reporters
  const r = await nodeTest([goodReal], env);
  assert.equal(r.status, 1, `the mutant's case fails the file:\n${r.out.slice(-2000)}`);
  const recs = readFileSync(join(scratch.dir, "results-functional.jsonl"), "utf8").trim().split("\n").map((l) => JSON.parse(l));
  assert.deepEqual(recs.map((x) => [x.id, x.status]).sort(), [[`${goodReal}::SF.1 a scratch case that passes`, "pass"], [`${goodReal}::SF.2 a scratch case the mutation turns red`, "fail"]], "ids carry the copy's absolute path, never a tracked spec's");
  const red = recs.find((x) => x.status === "fail");
  const evDir = red.evidenceDir && (isAbsolute(red.evidenceDir) ? red.evidenceDir : join(REPO_ROOT, red.evidenceDir));
  assert.ok(evDir && evDir.startsWith(scratch.dir + "/"), `evidence under the scratch invocation: ${red.evidenceDir}`);
  const steps = readFileSync(join(evDir, "steps.md"), "utf8");
  assert.ok(steps.includes(`node e2e/run.mjs run --attach ${runId} --spec-file ${goodReal} --grep 'SF\\.2 a scratch case the mutation turns red'`), `the rerun names the copy:\n${steps.slice(0, 600)}`);
  assert.match(readFileSync(join(evDir, "error.txt"), "utf8"), /the mutant's oracle fails/);
  const merged = mergeRun(scratch.dir).summary;
  assert.deepEqual([merged.counts.pass, merged.counts.fail], [1, 1], "report <dir> reads the scratch invocation");

  // The run's own invocation, beside it: the merged view is only that one.
  const plain = createInvocation(runDir, { suite: "functional" });
  writeFileSync(join(plain.dir, "results-functional.jsonl"), JSON.stringify({ id: "e2e/specs/functional/x.spec.mjs::X.1 a real case", file: "e2e/specs/functional/x.spec.mjs", name: "X.1 a real case", path: ["X.1 a real case"], suite: "functional", status: "pass", at: new Date().toISOString() }) + "\n");
  assert.deepEqual(listInvocations(runDir), [plain.id]);
  assert.equal(runDirOf(runId), plain.dir, "report <runId> resolves the run's only invocation, not the scratch one");
  const view = mergeInvocations(runId).results;
  assert.deepEqual(view.cases.map((c) => [c.id, c.status]), [["e2e/specs/functional/x.spec.mjs::X.1 a real case", "pass"]], "no mutant's failure in the merged view");
  assert.equal(view.summary.invocations, 1);
});

function runMjs(args) {
  const home = tempDir("e2e-specfile-home-");
  const env = { ...process.env, HOME: home };
  delete env.NODE_TEST_CONTEXT;
  return spawnSync(process.execPath, [join(E2E_DIR, "run.mjs"), "run", ...args], { cwd: REPO_ROOT, env, encoding: "utf8", timeout: 60_000 });
}

test("NEGATIVE: run.mjs --spec-file refuses, with usage exit 2, before attaching to anything", () => {
  const cases = [
    [["--attach", NO_STACK, "--spec-file", "relative/m1.spec.mjs"], /e2e: --spec-file relative\/m1\.spec\.mjs: not an absolute path/],
    [["--attach", NO_STACK, "--spec-file", join(dir, "m5-relative.spec.mjs")], /e2e: .*m5-relative\.spec\.mjs:3 imports "\.\.\/\.\.\/lib\/test\.mjs", which is no file/],
    [["--attach", NO_STACK, "--spec-file", join(SPECS_DIR, "functional", "a18-stats.spec.mjs")], /e2e: .* is in e2e\/specs\/: run it with --spec/],
    [["--attach", NO_STACK, "--spec", "a18", "--spec-file", good], /e2e: --spec-file and --spec do not mix/],
    [["--attach", NO_STACK, "--suite", "smoke", "--spec-file", good], /e2e: --spec-file runs in one tier/],
  ];
  for (const [args, re] of cases) {
    const r = runMjs(args);
    assert.equal(r.status, 2, `${args.join(" ")}: exit ${r.status}\n${r.stderr}`);
    assert.match(r.stderr, re, args.join(" "));
    assert.doesNotMatch(r.stderr, /no stack|invocation /, "refused before attaching or making an invocation");
  }
  assert.ok(!existsSync(join(OUT_DIR, NO_STACK)), "nothing was written for the run id");
});
